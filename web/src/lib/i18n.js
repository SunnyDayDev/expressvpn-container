function detectLang() {
  const saved = localStorage.getItem('detour_lang')
  if (saved === 'en' || saved === 'ru') return saved
  return (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

export const lang = writable(detectLang())

export function setLang(l) {
  localStorage.setItem('detour_lang', l)
  lang.set(l)
}

export const t = derived(lang, (l) => (key) => dict[l][key] ?? dict.en[key] ?? key)
